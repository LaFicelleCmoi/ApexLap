import Foundation

/// Labels are localised by `Strings.glossaryCategory`.
public enum GlossaryCategory: String, CaseIterable, Sendable {
    case race, strategy, technical, flags, rules
}

public struct GlossaryTerm: Hashable, Sendable, Identifiable {
    public let term: L
    public let category: GlossaryCategory
    public let definition: L
    public var id: String { term.fr }

    public func matches(_ query: String, language: AppLanguage) -> Bool {
        term[language].matchesSearch(query) || definition[language].matchesSearch(query)
    }
}

